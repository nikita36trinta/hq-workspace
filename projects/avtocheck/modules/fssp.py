# Публичный портал ФССП. Запросов туда НЕ делаем (капча) — это только ссылка
# «источник» в отчёте, чтобы клиент мог проверить результат сам.
PORTAL_URL = "https://fssp.gov.ru/iss/ip"


@dataclass
class FSSPResult:
    status: str  # "found" | "not_found" | "not_checked"
    detail: str
    items: list[dict[str, Any]]
    source_url: str = PORTAL_URL


def _split_fio(full_name: str) -> tuple[str, str, str]:
    parts = [p for p in full_name.strip().split() if p]
    if len(parts) >= 3:
        return parts[0], parts[1], " ".join(parts[2:])
    if len(parts) == 2:
        return parts[0], parts[1], ""
    if len(parts) == 1:
        return parts[0], "", ""
    return "", "", ""


def _normalize_dob_iso(dob: str) -> str:
    """NewDB требует дату в формате YYYY-MM-DD."""
    for fmt in ("%d.%m.%Y", "%Y-%m-%d"):
        try:
            return dt.datetime.strptime(dob.strip(), fmt).strftime("%Y-%m-%d")
        except ValueError:
            continue
    return ""


