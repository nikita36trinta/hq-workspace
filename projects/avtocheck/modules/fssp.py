_NOM_RULES = (("ой области", "ая область"), ("ому краю", "ий край"),
              ("ской Республике", "ская Республика"), ("ой Республике", "ая Республика"),
              ("ому автономному округу", "ий автономный округ"),
              ("ой автономной области", "ая автономная область"),
              ("ому АО", "ий АО"), ("ой АО", "ая АО"))


def region_name(code: str) -> str:
    """Название региона в именительном падеже — для таблиц и подписей."""
    t = region_title(code)
    if not t:
        return ""
    if t in _NOM_EXC:
        return _NOM_EXC[t]
    if t.startswith("Республике "):
        return "Республика " + t[len("Республике "):]
    for dative, nominative in _NOM_RULES:
        if t.endswith(dative):
            return t[: -len(dative)] + nominative
    return t


# Части адреса, которые ВООБЩЕ могут быть субъектом: с пометкой «обл/край/респ/
# АО/округ» либо город федерального значения. Иначе «г Москва, ул Тверская»
# превращалось в Тверскую область, а «ул Московская» в Подмосковье — искали бы
# долги не в том регионе и показали бы человеку чужое «чисто».
_REGION_MARK = re.compile(
    r"(?:^|\W)(обл|область|области|край|крае|кр|респ|республик\w*|"
    r"ао|округ\w*|автономн\w*)(?:\W|$)"
)
_FED_CITIES: tuple[tuple[str, str], ...] = (
    ("санкт-петербург", "78"), ("санктпетербург", "78"), ("спб", "78"),
    ("севастополь", "82"), ("москва", "77"),   # ФССП: Крым и Севастополь = 82
)


def region_from_address(address: str) -> str:
    """Код субъекта по тексту адреса: 'Саратовская обл, г Саратов…' → '64'.

    Разбираем по частям, а не поиском по всей строке: субъектом считается
    только часть с пометкой региона или город федерального значения.
    Пусто, если субъект не назван — честнее не проверить, чем проверить
    не тот регион."""
    raw = (address or "").lower().replace("ё", "е")
    for part in [p.strip() for p in raw.split(",") if p.strip()]:
        for name, code in _FED_CITIES:
            if name in part:
                return code
        if _REGION_MARK.search(part):
            for name, code in _REGION_SORTED:
                if name in part:
                    return code
    return ""


def region_from_kadastr(object_ref: str) -> str:
    """Код региона для ФССП из кадастрового номера (первые 2 цифры до ':').

    '77:01:0004012:1122' → '77'. Если это не кадастр — пусто.
    Для регионов, где кадастровый округ не совпадает с кодом субъекта,
    возвращается код субъекта (см. _CAD_TO_REGION).
    """
    m = re.match(r"\s*(\d{2})\s*:", object_ref or "")
    if not m:
        return ""
    cad = m.group(1)
    return _CAD_TO_REGION.get(cad, cad)


# Кэш результатов на 24ч — не жжём платные запросы на повтор того же человека.
_CACHE: dict[str, tuple[float, FSSPResult]] = {}
_CACHE_TTL = 24 * 3600


def check_enforcement(
    full_name: str, dob: str, regioncode: str = "", timeout: float = 300.0
) -> FSSPResult:
    ck = f"{full_name.strip().lower()}|{dob.strip()}|{regioncode}"
    hit = _CACHE.get(ck)
    if hit and (time.time() - hit[0]) < _CACHE_TTL:
        return hit[1]
    res = _check_live(full_name, dob, regioncode, timeout)
    if res.status in ("found", "not_found"):
        _CACHE[ck] = (time.time(), res)
    return res


def _check_live(full_name: str, dob: str, regioncode: str, timeout: float) -> FSSPResult:
    if not newdb.token():
        return FSSPResult(
            status="not_checked",
            detail="ФССП: проверка временно недоступна (не настроен доступ к базе).",
            items=[],
        )
    last, first, patr = _split_fio(full_name)
    dob_iso = _normalize_dob_iso(dob)
    if not last or not first or not dob_iso:
        return FSSPResult(
            status="not_checked",
            detail="ФССП: недостаточно данных (нужны Фамилия, Имя и дата рождения)",
            items=[],
        )
    # Отчество обязательно: NewDB отвечает «secondname must be non-empty» ещё до
    # поиска. Ловим ЗДЕСЬ, а не по HTTP 400, потому что в отчёт и в лог уходило
    # «ФССП: сервис недоступен (HTTP 400)» — будто сломался источник. По этой
    # формулировке заказ 4d697ef232d4 сначала пошли искать в балансе NewDB.
    # Запрос всё равно не состоится, так что и денег он не стоит.
    if not patr:
        return FSSPResult(
            status="not_checked",
            detail=("ФССП: нужно отчество продавца — государственные базы ищут "
                    "только по полному ФИО."),
            items=[],
        )
    if not regioncode:
        return FSSPResult(
            status="not_checked",
            detail=(
                "ФССП: не удалось определить регион для поиска. Укажите "
                "кадастровый номер объекта — по нему определяется регион."
            ),
            items=[],
        )

    # Через общий newdb.call, а не своей копией транспорта. Копия отстала от
    # оригинала в трёх местах, и каждое стоило денег:
    #   1. не размыкала поллинг на state="failed" (newdb.py умеет) — досиживала
    #      90с по заведомо мёртвому запросу и уходила на ВТОРУЮ платную попытку;
    #   2. ретраила ЛЮБОЕ исключение, включая обрыв связи уже ПОСЛЕ принятого
    #      (оплаченного) submit — платили второй раз за возможно готовый результат.
    #      newdb.call повторяет только NewDBTimeout;
    #   3. не звала _log_call, поэтому ФССП — самый частый метод, он идёт на каждой
    #      покупке — вообще не попадала в журнал списаний newdb_calls.jsonl.
    # ОДНА попытка на всё время ожидания, а не две по половине: submit
    # тарифицируется сразу, а повтор не ускоряет источник — он лишь покупает
    # вторую очередь к тому же тормозящему Росреестру. Не успели — requestId
    # записан, результат забирается позже бесплатно (newdb.fetch).
    try:
        rows = newdb.call("fssp_person", {
            "country": "ru",
            "lastname": last,
            "firstname": first,
            "secondname": patr,
            "dob": dob_iso,
            "regioncode": str(regioncode),
        }, timeout=timeout, attempts=1)
    except newdb.NewDBError as e:
        return FSSPResult(
            status="not_checked",
            detail=f"ФССП: сервис недоступен ({e}).",
            items=[],
        )
    return _summarize(rows, str(regioncode))


def _summarize(rows: list[dict[str, Any]], regioncode: str = "") -> FSSPResult:
    # Поиск идёт по ОДНОМУ региону — тому, где находится объект. Долги того же
    # человека в соседней области мы не увидим, поэтому «не найдено» без
    # оговорки читалось бы как «чист по стране». Это не так.
    where = region_title(regioncode)
    scope = f" (поиск по {where})" if where else ""
    if not rows:
        return FSSPResult(
            status="not_found",
            detail="ФССП: исполнительных производств не найдено" + scope,
            items=[],
        )
    items: list[dict[str, Any]] = []
    active = 0
    active_sum = 0.0
    for row in rows:
        completed = bool((row.get("CompletionDateOrReason") or "").strip())
        subj = row.get("SubjectAndDebtAmount", "") or ""
        # Первая сумма «N руб» = основной долг (исполнительский сбор идёт после).
        amount = 0.0
        m = re.search(r"([\d][\d\s]*[.,]\d{2})\s*руб", subj, re.I)
        if m:
            try:
                amount = float(m.group(1).replace(" ", "").replace(",", "."))
            except ValueError:
                amount = 0.0
        if not completed:
            active += 1
            active_sum += amount
        items.append(
            {
                "debtor": row.get("Debtor", ""),
                "case": row.get("EnforcementProceeding", ""),
                "subject": subj,
                "status": "завершено" if completed else "не завершено",
                "bailiff": row.get("BailiffDepartment", ""),
            }
        )
    detail = (
        f"ФССП: найдено производств{scope} — {len(rows)}"
        + (
            f"; действующих — {active}, непогашенный долг — "
            f"{active_sum:,.0f} ₽".replace(",", " ")
            if active
            else "; все завершены"
        )
    )
    return FSSPResult(status="found", detail=detail, items=items[:15])
