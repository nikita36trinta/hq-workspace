STATUS_WORD = {"found": "обнаружено", "not_found": "чисто",
               "not_checked": "нет данных", "locked": "не входит в тариф"}

# Находка в этих блоках сделку не запрещает, а влияет на цену: метка жёлтая,
# а не красная. Иначе «был в такси» кричит так же громко, как «в залоге».
SOFT = {"dtp", "history", "taxi", "customs", "mileage"}

# Дату актуальности кладёт в текст _tail() из modules/auto.py — формат наш и
# фиксированный. Вынимаем её отдельным полем, чтобы она читалась с одного
# взгляда, а не терялась в конце абзаца. Меняете _tail — правьте и это.
_ASOF_RE = re.compile(
    r"\s*(⚠️\s*)?Данные актуальны на (\d{2}\.\d{2}\.\d{4})[^.]*\.\s*"
    r"(Сведения могли измениться;[^.]*\.)?"
)


def split_detail(detail: str) -> dict:
    """Разделить текст проверки на суть и дату актуальности."""
    t = str(detail or "")
    m = _ASOF_RE.search(t)
    if not m:
        return {"text": t.strip(), "date": "", "old": False}
    return {"text": _ASOF_RE.sub(" ", t).strip(), "date": m.group(2), "old": bool(m.group(1))}


def tile(key: str, status: str, detail: str) -> dict:
    """Готовая плитка проверки: заголовок, объяснение, дата актуальности."""
    s = split_detail(detail)
    title = (TITLES.get(key) or {}).get(status) or (s["text"].split(".")[0] if s["text"] else "")
    return {
        "title": title,
        "means": (MEANS.get(key) or {}).get(status, ""),
        "asof": s["date"],
        "asof_old": s["old"],
        "text": s["text"],
        "word": STATUS_WORD.get(status, status),
        "soft": key in SOFT,
    }
