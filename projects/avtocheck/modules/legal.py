def _code_of(item: Any) -> str:
    """Код обременения по записи ЕГРН: сначала как код, потом по ярлыку."""
    raw = ""
    if isinstance(item, dict):
        raw = str(item.get("type") or "")
        label = str(item.get("encumbranceTypeDesc") or "")
    else:
        label = ""
    head = raw[:6]
    if head in _BY_CODE:
        return head
    hay = (raw + " " + label).lower()
    for needle, code in _BY_TEXT:
        if needle in hay:
            return code
    return head


def consequences(checks: list[Any]) -> list[Consequence]:
    """Последствия по результатам проверок. Порядок: сначала блокирующие.

    checks — список объектов/словарей с полями key, status, items (как в отчёте).
    Возвращает только то, для чего есть выверенная формулировка: молчание здесь
    лучше выдуманного вывода."""
    from modules import rosreestr

    out: list[Consequence] = []
    seen: set[str] = set()

    def _get(c: Any, name: str, default=None):
        return c.get(name, default) if isinstance(c, dict) else getattr(c, name, default)

    for c in checks or []:
        key, status = _get(c, "key"), _get(c, "status")
        detail = str(_get(c, "detail") or "")

        if key == "object" and status == "found":
            for it in _get(c, "items") or []:
                code = _code_of(it)
                cons = _BY_CODE.get(code)
                if cons and code not in seen:
                    seen.add(code)
                    out.append(cons)
            # долевую rosreestr не кладёт в items — она видна по тексту вывода
            if "долев" in detail.lower() and "shared" not in seen:
                seen.add("shared")
                out.append(_SHARED)

        elif key == "bankruptcy" and status == "found" and "bankr" not in seen:
            seen.add("bankr")
            out.append(_BANKRUPTCY)

        elif key == "enforcement" and status == "found" and "enf" not in seen:
            seen.add("enf")
            out.append(_ENFORCEMENT)

    out.sort(key=lambda c: 0 if c.severity == "block" else 1)
    return out


def norms_html(cons: Consequence) -> str:
    """Строка со ссылками на нормы. Пусто, если норм нет — и это нормально."""
    from html import escape
    parts = []
    for n in cons.norms:
        parts.append(
            f'<a href="{escape(n.url)}" target="_blank" rel="noopener">{escape(n.label)}</a>'
            + (f' <span class="nnote">{escape(n.note)}</span>' if n.note else "")
        )
    return " · ".join(parts)
