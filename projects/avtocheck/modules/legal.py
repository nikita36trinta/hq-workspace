@dataclass(frozen=True)
class Norm:
    """Норма закона: как её назвать, куда сослаться, когда сверяли."""
    label: str
    url: str
    verified: str = VERIFIED_AT
    note: str = ""          # оговорка, если типовое правило знает исключения


@dataclass
class Consequence:
    """Что произойдёт при сделке и на основании чего."""
    text: str
    norms: list[Norm] = field(default_factory=list)
    severity: str = "warn"  # "block" — сделка невозможна | "warn" — требует действий


