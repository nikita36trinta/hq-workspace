"""
Пакет к сделке — что делать покупателю после того, как отчёт готов.

ЗАЧЕМ. Отчёт отвечает на вопрос «чисто ли», и на этом обрывается. Человек узнаёт
«долевая собственность, доли 1/2 и 1/2» — и остаётся один на один с вопросом, что
теперь спрашивать у продавца. Мы единственные, кто в этот момент знает про его
объект всё, и ничего ему с этим знанием не даём.

ПРИНЦИП. Каждый пункт выводится ИЗ НАХОДКИ по конкретному объекту. Пункт, который
одинаков для всех, — наполнитель: за общие статьи «как купить квартиру» второй раз
не платят. Поэтому здесь нет ни одного правила без условия.

ЧЕГО ЗДЕСЬ НЕТ. Юридической консультации: у нас нет человека в цикле, и обещать её
нельзя. Пакет говорит, ЧТО спросить и ЗАЧЕМ, а не «как вам следует поступить».

Движок детерминированный: одни и те же факты дают один и тот же пакет. Модель
подключается отдельно и только для связного текста — решения принимают правила.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any


@dataclass
class Item:
    """Один пункт пакета."""
    title: str                  # что именно запросить/проверить
    why: str                    # зачем — риск, который это закрывает
    law: str = ""               # норма, если она есть и уместна
    urgent: bool = False        # до аванса, а не «когда-нибудь»


@dataclass
class Kit:
    ask_seller: list[Item] = field(default_factory=list)    # запросить у продавца
    check_self: list[Item] = field(default_factory=list)    # проверить самому
    day_of: list[str] = field(default_factory=list)         # чек-лист дня сделки
    letters: dict[str, str] = field(default_factory=dict)   # готовые тексты
    facts: dict[str, Any] = field(default_factory=dict)     # что нашли (для шапки)

    def is_empty(self) -> bool:
        return not (self.ask_seller or self.check_self)

    def to_dict(self) -> dict[str, Any]:
        conv = lambda xs: [{"title": i.title, "why": i.why, "law": i.law,
                            "urgent": i.urgent} for i in xs]
        return {"ask_seller": conv(self.ask_seller), "check_self": conv(self.check_self),
                "day_of": self.day_of, "letters": self.letters, "facts": self.facts}


# ---------------------------------------------------------------- факты из отчёта

_ENC_MORTGAGE = ("ипотек",)
_ENC_BLOCKING = ("арест", "запрещен", "запрет", "изъят")
_ENC_RENT = ("рента", "пожизненн")
_ENC_LEASE = ("аренда", "наём", "найм")


def _years_since(date_str: str) -> float | None:
    """Сколько лет прошло с даты. None — если дату не разобрали."""
    s = (date_str or "").strip()
    if not s:
        return None
    for fmt in ("%Y-%m-%d", "%d.%m.%Y", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M:%SZ"):
        try:
            d = datetime.strptime(s[:len(fmt) + 2].strip("Z"), fmt)
        except ValueError:
            continue
        return (datetime.now(timezone.utc).replace(tzinfo=None) - d).days / 365.25
    return None


def _human_date(date_str: str) -> str:
    """ISO-дату — в привычный вид. В тексте для человека «2024-11-02» выглядит как
    отладочный вывод, а не как дата регистрации права."""
    s = (date_str or "").strip()
    for fmt in ("%Y-%m-%d", "%Y-%m-%dT%H:%M:%S"):
        try:
            return datetime.strptime(s[:len(fmt) + 2].strip("Z"), fmt).strftime("%d.%m.%Y")
        except ValueError:
            continue
    return s


def facts_from_report(rec: dict[str, Any]) -> dict[str, Any]:
    """Собрать факты из записи отчёта: превью + результаты проверок.

    Читаем структурированные поля, а не текст заключения: формулировки мы правим
    часто, и пакет, разбирающий собственную прозу, сломается на первой же правке.
    """
    checks = rec.get("checks") or []
    obj_check = next((c for c in checks if c.get("key") == "object"), {}) or {}
    prev = rec.get("object_preview") or {}

    encs: list[str] = []
    for it in (obj_check.get("items") or []):
        if isinstance(it, dict):
            encs.append(str(it.get("type") or ""))
        else:
            encs.append(str(it))
    enc_text = " ".join(encs).lower()

    # Долевую берём из поля, а если отчёт старый и поля нет — из текста: там эта
    # формулировка наша собственная и стабильная («долевая собственность (доли: …)»).
    detail = str(obj_check.get("detail") or "")
    shared = bool(obj_check.get("shared"))
    if not shared:
        # ТОЛЬКО точная формулировка находки «долевая собственность (…)». Поиск по
        # подстроке «долев» давал ложное срабатывание: в хвосте заключения есть общее
        # предупреждение «…долевая — нужны согласия всех», и объект с одной лишь
        # ипотекой получал требование отказов сособственников, которых не существует.
        shared = bool(re.search(r"долевая собственность\s*\(", detail, re.I))
    parts = obj_check.get("parts") or []
    if not parts:
        m = re.search(r"доли:\s*([^)]+)\)", detail)
        if m:
            parts = [p.strip() for p in m.group(1).split(",") if p.strip()]

    kind = str(prev.get("type") or "").lower()
    purpose = str(prev.get("purpose") or "").lower()

    return {
        "found": obj_check.get("status") in ("found", "not_found"),
        "cad": prev.get("cad") or obj_check.get("cadnum") or "",
        "address": prev.get("address") or "",
        "area": prev.get("area"),
        "floor": prev.get("floor"),
        "shared": shared,
        "parts": parts,
        "owners_n": int(obj_check.get("owners_n") or 0),
        "joint": any("совместн" in str(p).lower() for p in parts),
        "reg_date": obj_check.get("reg_date") or prev.get("reg_date") or "",
        "encumbrances": [e for e in encs if e],
        "has_mortgage": any(k in enc_text for k in _ENC_MORTGAGE),
        "has_blocking": any(k in enc_text for k in _ENC_BLOCKING),
        "has_rent": any(k in enc_text for k in _ENC_RENT),
        "has_lease": any(k in enc_text for k in _ENC_LEASE),
        "is_land": bool(prev.get("is_land")) or "участок" in kind,
        "is_building": "здани" in kind or "дом" in kind,
        "non_residential": bool(purpose) and "жил" not in purpose,
        "heritage": bool(prev.get("heritage")),
        "year_built": prev.get("year_built"),
        # Продавец: проверялся только в полном тарифе.
        "seller_checked": any(c.get("key") == "enforcement" for c in checks),
        "seller_debts": any(c.get("key") == "enforcement" and c.get("status") == "found"
                            for c in checks),
        "seller_bankrupt": any(c.get("key") == "bankruptcy" and c.get("status") == "found"
                               for c in checks),
        "seller_name": rec.get("seller_name") or "",
    }


# ---------------------------------------------------------------- правила

def build(rec: dict[str, Any]) -> Kit:
    """Собрать пакет по записи отчёта."""
    f = facts_from_report(rec)
    kit = Kit(facts=f)
    ask, own = kit.ask_seller, kit.check_self

    # --- то, что нужно по любому объекту, и это не наполнитель
    #
    # С марта 2023 года ЕГРН не раскрывает ФИО правообладателя третьим лицам
    # (ФЗ-266). Мы видим форму права, доли и обременения — но не имя. Значит
    # единственный способ убедиться, что перед покупателем собственник, а не
    # однофамилец с доверенностью, — выписка, которую продавец получил на себя.
    # Это ядро пакета: без него все остальные проверки проверяют не того человека.
    ask.append(Item(
        title="Свежая выписка ЕГРН, полученная продавцом на своё имя",
        why="Реестр не раскрывает имя собственника посторонним, поэтому наш отчёт "
            "показывает объект, но не подтверждает, что продаёт именно владелец. "
            "Сверьте в его выписке ФИО с паспортом, а кадастровый номер — с нашим "
            "отчётом: если объект в них разный, дальше идти нельзя.",
        law="ФЗ-266 от 14.07.2022", urgent=True))
    ask.append(Item(
        title="Документ, по которому продавец получил право",
        why="Договор купли-продажи, свидетельство о наследстве, договор дарения "
            "или приватизации. Проблемы прошлой сделки переходят к новому "
            "покупателю вместе с квартирой.",
        urgent=False))

    # --- права на объект
    if f["shared"]:
        doli = (", ".join(str(p) for p in f["parts"])) if f["parts"] else ""
        ask.append(Item(
            title="Отказы сособственников от преимущественного права"
                  + (f" (доли по ЕГРН: {doli})" if doli else ""),
            why="Доля продаётся только после того, как остальные собственники "
                "отказались её выкупить. Без отказов сделку можно оспорить в течение "
                "трёх месяцев, и покупателя заменят на сособственника.",
            law="ст. 250 ГК РФ", urgent=True))
        ask.append(Item(
            title="Нотариальная форма договора",
            why="Продажа доли постороннему лицу удостоверяется нотариусом. "
                "Договор в простой письменной форме Росреестр не зарегистрирует.",
            law="ст. 42 ФЗ-218", urgent=False))

    if f["joint"]:
        ask.append(Item(
            title="Нотариальное согласие супруга на продажу",
            why="В ЕГРН запись о совместной собственности. Без согласия второй "
                "супруг вправе оспорить сделку в течение года с момента, когда узнал.",
            law="ст. 35 СК РФ", urgent=True))
    elif not f["shared"]:
        # Условие было `owners_n == 1`, но в отчётах до 05.08.2026 этого поля нет,
        # и вопрос про брак молча пропадал — а он нужен по любой единоличной
        # продаже: запись в ЕГРН на одного супруга не делает квартиру личной.
        ask.append(Item(
            title="Свидетельство о браке или заявление, что в браке не состоял",
            why="Квартира, купленная в браке, считается совместной, даже если "
                "в ЕГРН записан один супруг. Тогда нужно нотариальное согласие второго.",
            law="ст. 34 СК РФ", urgent=True))

    if f["owners_n"] > 1 and f["seller_name"]:
        ask.append(Item(
            title="Доверенность, если продаёт не каждый собственник лично",
            why=f"В ЕГРН записей о правах: {f['owners_n']}, а продавец назван один. "
                "Доверенность проверяется по реестру Федеральной нотариальной палаты — "
                "отозванная выглядит так же, как действующая.",
            urgent=True))

    # --- обременения
    if f["has_blocking"]:
        ask.append(Item(
            title="Документ о снятии ареста или запрета регистрации",
            why="Пока запрет в ЕГРН, Росреестр приостановит переход права. "
                "Аванс до снятия отдавать нельзя — деньги уйдут, регистрация не пройдёт.",
            urgent=True))
    if f["has_mortgage"]:
        ask.append(Item(
            title="Справка банка об остатке долга и согласие залогодержателя",
            why="Квартира в залоге. Нужен порядок расчёта, при котором долг гасится "
                "и залог снимается до или одновременно с переходом права.",
            law="ст. 37 ФЗ-102", urgent=True))
    if f["has_rent"]:
        ask.append(Item(
            title="Договор ренты и согласие получателя ренты",
            why="Рента остаётся за объектом при смене собственника: платить будете вы, "
                "а получатель ренты сохраняет право проживания.",
            law="ст. 586 ГК РФ", urgent=True))
    if f["has_lease"]:
        ask.append(Item(
            title="Договор аренды и срок его окончания",
            why="Аренда переходит вместе с объектом. Въехать до конца срока не выйдет, "
                "даже если арендатор о нём не знает.",
            law="ст. 617 ГК РФ", urgent=False))

    # --- история права
    yrs = _years_since(f["reg_date"])
    if yrs is not None and yrs < 3:
        ask.append(Item(
            title="Документ-основание: на чём продавец получил право",
            why=f"Право зарегистрировано {_human_date(f['reg_date'])} — меньше трёх лет "
                f"назад. "
                "Срок оспаривания предыдущей сделки не истёк, и её проблемы перейдут "
                "к вам вместе с квартирой.",
            urgent=True))
        ask.append(Item(
            title="Если основание — наследство: справка нотариуса о круге наследников",
            why="Наследник, не заявившийся вовремя, вправе восстановить срок и "
                "потребовать долю. Это самый частый повод отобрать квартиру у покупателя.",
            law="ст. 1155 ГК РФ", urgent=True))
    elif yrs is not None and yrs < 1:
        ask.append(Item(
            title="Причина быстрой перепродажи",
            why=f"Право зарегистрировано меньше года назад ({_human_date(f['reg_date'])}). "
                "Быстрая перепродажа бывает нормальной, но требует объяснения.",
            urgent=False))

    # --- назначение и тип
    if f["non_residential"]:
        ask.append(Item(
            title="Подтверждение назначения помещения",
            why="По ЕГРН назначение нежилое. Прописаться нельзя, ипотеку большинство "
                "банков не даст, ЖКУ считают по тарифам для юридических лиц.",
            urgent=True))
    if f["is_land"]:
        ask.append(Item(
            title="Межевание и акт согласования границ со смежниками",
            why="Участок без установленных границ — источник спора с соседями, "
                "который переходит к новому собственнику.",
            urgent=False))
    if f["heritage"]:
        ask.append(Item(
            title="Охранное обязательство",
            why="Объект культурного наследия: ремонт, окна и фасад согласуются "
                "с органом охраны, нарушение — штраф и требование вернуть как было.",
            urgent=False))

    # --- продавец (полный тариф)
    if f["seller_debts"]:
        ask.append(Item(
            title="Справка от приставов об оплате задолженности",
            why="У продавца исполнительные производства. Если его признают банкротом "
                "в течение трёх лет, сделку могут оспорить как вывод имущества.",
            law="ст. 61.2 ФЗ-127", urgent=True))

    # --- то, что мы проверить не можем: реестры закрыты для третьих лиц
    own.append(Item(
        title="Справка о зарегистрированных лицах (выписка из домовой книги)",
        why="Показывает, кто прописан. Отдельно спросите про отказавшихся от "
            "приватизации: за ними сохраняется пожизненное право проживания, "
            "и выселить их нельзя даже через суд.",
        law="ст. 19 ФЗ-189", urgent=True))
    own.append(Item(
        title="Справки об отсутствии долгов по ЖКУ и взносам на капремонт",
        why="Долг по капремонту переходит к новому собственнику вместе с квартирой, "
            "в отличие от остальных коммунальных долгов.",
        law="ч. 3 ст. 158 ЖК РФ", urgent=False))
    if f["owners_n"] > 1 or f["shared"]:
        own.append(Item(
            title="Согласие органов опеки, если среди собственников несовершеннолетний",
            why="Без согласия опеки сделку признают недействительной, и вернуть "
                "деньги будет сложнее, чем квартиру.",
            law="ст. 37 ГК РФ", urgent=True))
    own.append(Item(
        title="Справки из психоневрологического и наркологического диспансеров",
        why="Нужны, если продавец пожилой или что-то в поведении настораживает: "
            "сделку оспаривают по неспособности понимать значение своих действий.",
        law="ст. 177 ГК РФ", urgent=False))

    # --- день сделки: одинаково для всех, но это не наполнитель, а порядок действий
    # Заглушку «кадастровый номер из отчёта» не пишем: строка, которая ничего не
    # сверяет, только занимает место в чек-листе.
    kit.day_of = []
    if f["cad"]:
        kit.day_of.append(f"Сверьте в договоре кадастровый номер: должен быть {f['cad']}")
    kit.day_of += [
        "Закажите свежую выписку ЕГРН в день подписания — наша проверка "
        "показывает состояние на дату отчёта, а арест может лечь за сутки",
        "Расчёт через аккредитив, эскроу или ячейку с условием доступа "
        "по зарегистрированному переходу права",
        "Аванс — только по письменному соглашению, где указано, за что он и "
        "при каких условиях возвращается",
    ]
    kit.letters = _letters(f, ask)
    return kit


def _letters(f: dict[str, Any], ask: list[Item]) -> dict[str, str]:
    """Готовые тексты: скопировал и отправил."""
    obj = f["address"] or f["cad"] or ""
    lines = [f"— {i.title}" for i in ask] or ["— свежая выписка из ЕГРН"]
    where = f" по адресу: {obj}" if obj else ""
    to_seller = (
        "Здравствуйте! Планирую покупку" + where + ".\n"
        "Перед авансом прошу подготовить документы:\n"
        + "\n".join(lines) +
        "\n\nЭто стандартный набор для регистрации перехода права — "
        "без них Росреестр приостановит сделку."
    )
    to_uk = (
        "Здравствуйте! Прошу предоставить сведения по помещению"
        + (f" {obj}" if obj else "") + ":\n"
        "— задолженность по коммунальным услугам и взносам на капитальный ремонт;\n"
        "— сведения о зарегистрированных лицах;\n"
        "— проводился ли капитальный ремонт дома и когда запланирован следующий."
    )
    return {"продавцу": to_seller, "в управляющую компанию": to_uk}
