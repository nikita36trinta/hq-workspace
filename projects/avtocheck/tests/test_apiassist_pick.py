"""Тесты отбора объекта из адресной выдачи api-assist.

Проверяем две стороны: находим ли верную строку среди похожих и, что важнее,
НЕ берём ли чужой дом. Второе критичнее: отчёт про чужую квартиру хуже отказа.
"""
import sys
sys.path.insert(0, str(__import__('pathlib').Path(__file__).resolve().parent.parent))
from modules.apiassist import pick_object, _house_of, _bldg_of, _flat_of

ok = bad = 0


def check(name, got, want):
    global ok, bad
    good = got == want
    ok, bad = ok + good, bad + (not good)
    print(("  ok    " if good else "  ОШИБКА ") + "%-56s → %r%s" % (
        name[:54], got, "" if good else f"  (ждали {want!r})"))


print("РАЗБОР АДРЕСА")
check("ввод «д 5 к 5, кв 24» → дом", _house_of("Дачный пр-кт, д 5 к 5, кв 24"), "5")
check("ввод «д 5 к 5, кв 24» → корпус", _bldg_of("Дачный пр-кт, д 5 к 5, кв 24"), "5")
check("ответ «д. 5, корп. 5, литера. А, кв. 24» → дом",
      _house_of("Санкт-Петербург, пр-кт. Дачный, д. 5, корп. 5, литера. А, кв. 24"), "5")
check("ответ «д. 5, корп. 5, литера. А, кв. 24» → корпус",
      _bldg_of("Санкт-Петербург, пр-кт. Дачный, д. 5, корп. 5, литера. А, кв. 24"), "5")
check("дом с дефисом «д 10-12 к 7»", _house_of("Тихвинский пер, д 10-12 к 7"), "10-12")
check("дом с литерой «дом 5а»", _house_of("ул Мира, дом 5а, кв 1"), "5а")
check("корпуса нет", _bldg_of("ул Мира, дом 5, кв 1"), "")
check("квартира из «помещ 2а»", _flat_of("Тихвинский пер, д 10-12 к 7, помещ 2а"), "2а")

print("\nОТБОР ИЗ ВЫДАЧИ")
Q = "г Санкт-Петербург, Дачный пр-кт, д 5 к 5, кв 24"
rows_real = [
    {"cad_number": "78:15:0008431:8527", "address": "Санкт-Петербург, пр-кт. Дачный, д. 5, корп. 5, литера. А, кв. 24"},
    {"cad_number": "78:15:0008431:9301", "address": "Санкт-Петербург, пр-кт. Дачный, д. 9, корп. 5, литера. А, кв. 24"},
    {"cad_number": "78:15:0008408:5180", "address": "Санкт-Петербург, пр-кт. Дачный, д. 16, корп. 5, литера. А, кв. 24"},
    {"cad_number": "78:15:0008431:8837", "address": "Санкт-Петербург, пр-кт. Дачный, д. 5, корп. 4, литера. А, кв. 24"},
    {"cad_number": "78:15:0008436:6758", "address": "Санкт-Петербург, пр-кт. Дачный, д. 21, корп. 5, литера. А, кв. 24"},
]
got = pick_object(rows_real, Q)
check("верная строка среди пяти «квартир 24»", (got or {}).get("cad_number"), "78:15:0008431:8527")

# Чужой дом единственным ответом — раньше он бы прошёл как len(rows)==1
check("единственный ответ, но ЧУЖОЙ дом",
      pick_object([{"cad_number": "78:15:0000000:1",
                    "address": "Санкт-Петербург, пр-кт. Дачный, д. 9, корп. 5, кв. 24"}], Q),
      None)
check("единственный ответ, дом верный",
      (pick_object([{"cad_number": "78:15:0008431:8527",
                     "address": "Санкт-Петербург, пр-кт. Дачный, д. 5, корп. 5, кв. 24"}], Q) or {}).get("cad_number"),
      "78:15:0008431:8527")
check("две строки, обе подходят под дом+корпус+кв → отказ",
      pick_object([{"cad_number": "1", "address": "пр-кт. Дачный, д. 5, корп. 5, кв. 24"},
                   {"cad_number": "2", "address": "пр-кт. Дачный, д. 5, корп. 5, кв. 24"}], Q),
      None)
check("нужной квартиры в выдаче нет",
      pick_object([{"cad_number": "1", "address": "пр-кт. Дачный, д. 5, корп. 5, кв. 88"}], Q),
      None)
check("корпус не указан в ответе — принимаем по дому и квартире",
      (pick_object([{"cad_number": "77:01:1", "address": "пр-кт. Дачный, д. 5, кв. 24"}], Q) or {}).get("cad_number"),
      "77:01:1")
check("запрос без квартиры (дом целиком) → отказ",
      pick_object(rows_real, "г Санкт-Петербург, Дачный пр-кт, д 5 к 5"), None)
check("пустая выдача", pick_object([], Q), None)

print("\n" + "=" * 78)
print(f"пройдено {ok}, провалено {bad}")
sys.exit(1 if bad else 0)
